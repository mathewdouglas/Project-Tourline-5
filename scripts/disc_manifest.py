"""Write the reference list of a known-good GT5 disc folder.

    python scripts/disc_manifest.py "<disc folder or its PS3_GAME>"

Writes config/gt5-disc.json (every disc file under PS3_GAME: relative path,
size, SHA-256, sample SHA-256) and launcher/disc_files.h (the files the
engine reads, which the launcher checks: launcher/disc_check.h). No game
content is stored. Regenerate only from a dump whose disc image matches Redump.

Only USRDIR/GT.VOL and USRDIR/MOVIE are checked by the launcher. The other
files are either unused by the engine (EBOOT.BIN, LICDIR, icons, trophies),
verified elsewhere (INSDIR/DATA000.PKG at setup) or may legitimately differ
between folder-dump tools (PARAM.SFO, which setup reads by title and version).
Decrypted executables left in the dump (*.elf) are not disc files.
"""
import hashlib
import json
import sys
from pathlib import Path

SAMPLES, SAMPLE_BYTES = 8, 65536


def checked(relative):
    return relative == 'USRDIR/GT.VOL' or relative.startswith('USRDIR/MOVIE/')


def sample_sha256(path, size):
    """SHA-256 of 8 x 64 KiB spread evenly over the file (the whole file when
    smaller). Must match disc_check::sample_sha256 in launcher/disc_check.h.
    Files extracted from an encrypted disc image keep their sizes but not
    their bytes; a sample shows that without reading the whole file."""
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        if size <= SAMPLES * SAMPLE_BYTES:
            h.update(f.read())
        else:
            for i in range(SAMPLES):
                f.seek(i * (size - SAMPLE_BYTES) // (SAMPLES - 1))
                h.update(f.read(SAMPLE_BYTES))
    return h.hexdigest()


def main():
    root = Path(__file__).resolve().parents[1]
    disc = Path(sys.argv[1])
    if (disc / 'PS3_GAME').is_dir():
        disc = disc / 'PS3_GAME'
    if not (disc / 'PARAM.SFO').is_file():
        sys.exit(f'not a PS3_GAME folder: {disc}')

    files = []
    paths = sorted(p for p in disc.rglob('*') if p.is_file() and p.suffix.lower() != '.elf')
    total = sum(p.stat().st_size for p in paths)
    done = 0
    for p in paths:
        h = hashlib.sha256()
        with open(p, 'rb') as f:
            while chunk := f.read(8 << 20):
                h.update(chunk)
                done += len(chunk)
                print(f'\r{done * 100 // max(total, 1):3d}% {p.name[:40]:40s}', end='', file=sys.stderr, flush=True)
        relative = p.relative_to(disc).as_posix()
        files.append({'path': relative, 'bytes': p.stat().st_size, 'sha256': h.hexdigest(),
                      'sample_sha256': sample_sha256(p, p.stat().st_size), 'checked': checked(relative)})
    print(file=sys.stderr)

    out = {
        'title_id': 'BCUS98114',
        'disc_version': '02.00',
        'source': 'Redump-named dump "Gran Turismo 5 (USA) (En,Ja,Fr,Es,Pt) (v02.00)", PS3_GAME folder',
        'files': files,
    }
    (root / 'config' / 'gt5-disc.json').write_text(json.dumps(out, indent=2) + '\n', encoding='utf-8')

    lines = [
        '// Generated by scripts/disc_manifest.py from config/gt5-disc.json. No game content.',
        '// The retail BCUS98114 v02.00 disc files the engine reads, relative to PS3_GAME.',
        '#pragma once',
        '// sample: SHA-256 of 8 x 64 KiB spread over the file (disc_check::sample_sha256).',
        'struct DiscFile { const wchar_t* path; unsigned long long bytes; const wchar_t* sha256; const wchar_t* sample; };',
        'static const DiscFile disc_files[] = {',
    ]
    for f in files:
        if f['checked']:
            lines.append(f'    {{L"{f["path"]}", {f["bytes"]}ull, L"{f["sha256"]}", L"{f["sample_sha256"]}"}},')
    lines.append('};')
    (root / 'launcher' / 'disc_files.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(files)} files ({sum(f["checked"] for f in files)} checked), {total} bytes')


if __name__ == '__main__':
    main()
