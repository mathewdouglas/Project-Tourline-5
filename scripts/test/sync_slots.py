"""Build the real sys_lwcond/sys_lwmutex handlers and replay issues
#34/#37/#43: once the runtime's slot tables filled, a wait on a new lwcond
returned at once and a new lwmutex locked nothing.

PS3_LWCOND_SLOT_FREE=0 PS3_LWM_SLOT_FREE=0 must reproduce both; the default
must not. Separate processes, because the switches are read once."""
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
runtime = Path(os.environ.get('PS3RECOMP_DIR', root.parent / 'ps3recomp-tourline5'))
(root / 'scratch').mkdir(exist_ok=True)
folder = Path(tempfile.mkdtemp(prefix='sync-slots-', dir=root / 'scratch'))
src = runtime / 'runtime' / 'ppu' / 'ppu_sysprx.cpp'
# ppu_recomp.h is generated by the lift; the handlers need only the context.
(folder / 'ppu_recomp.h').write_text(
    '#pragma once\n#include "ppu_context.h"\n'
    'extern "C" uint8_t vm_read8(uint64_t a);\nextern "C" void vm_write8(uint64_t a, uint8_t v);\n',
    encoding='ascii')
batch = folder / 'build.cmd'
batch.write_text(
    '@echo off\ncall "C:\\Program Files\\Microsoft Visual Studio\\2022\\Community\\VC\\Auxiliary\\Build\\vcvars64.bat" >nul\n'
    '"C:\\Program Files\\LLVM\\bin\\clang-cl.exe" /nologo /O2 /MD /EHsc /std:c++17 /D_CRT_SECURE_NO_WARNINGS '
    '-Wno-everything '
    f'/I"{folder}" /I"{runtime}/runtime/ppu" /I"{runtime}/runtime" /I"{runtime}/runtime/memory" /I"{runtime}/include" '
    f'/FI"{src}" /Fo"{folder}/" /Fe"{folder}/test.exe" '
    f'"{root}/scripts/test/sync_slots.cpp" /link /FORCE:UNRESOLVED\n',
    encoding='ascii')
subprocess.run(['cmd', '/c', str(batch)], check=True, cwd=root)
for mode in ('0', '1'):
    env = os.environ.copy()
    env['PS3_LWCOND_REAL'] = '1'
    env['PS3_LWCOND_SLOT_FREE'] = mode
    env['PS3_LWM_SLOT_FREE'] = mode
    for k in ('PS3_LWM_FUTEX', 'PS3_LWM_CHECK', 'PS3_LWMUTEX_TRACE', 'PS3_LWM_TRACE',
              'PS3_LWCOND_TRACE', 'PS3_LWM_HOST_STATE'):
        env.pop(k, None)
    subprocess.run([str(folder / 'test.exe'), mode], env=env, check=True, timeout=120)
print('sync_slots: passed')
