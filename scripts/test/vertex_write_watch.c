static void reservation_test(int mode)
{
    /* The real vm_init reservation loop, without committing/zeroing its full
     * 256 MB main memory. Commit one page to test its actual tracking flags. */
#include "vertex_watch_reserve.inc"
    CHECK(vm_base && ((uintptr_t)vm_base & 0xFFFFFFFFull) == 0);
    CHECK(VirtualAlloc(vm_base + 0x10000, 4096, MEM_COMMIT, PAGE_READWRITE));
    vm_base[0x10000] = 1;
    void* pages[1]; ULONG_PTR n = 1; ULONG gran;
    UINT result = GetWriteWatch(WRITE_WATCH_FLAG_RESET, vm_base + 0x10000, 4096, pages, &n, &gran);
    const int expected = mode > 0 && mode <= 2 && !getenv("PS3_NO_WRITE_WATCH");
    CHECK(expected ? result == 0 && n == 1 : result != 0);
    VirtualFree(vm_base, 0, MEM_RELEASE); vm_base = NULL;
    printf("PASS actual vm_init reservation: mode=%d tracked=%d 4GB-aligned\n", mode, expected);
}

static void tracker_tests(void)
{
    RsxWriteWatch* w = calloc(1, sizeof(*w));
    CHECK(w && rsx_ww_init(w, vm_base, 0x100000000ull));
    RsxWwRange a[] = {{0x1000, 64}}, b[] = {{0x1080, 64}};
    RsxWwSnapshot sa = {0}, sb = {0};
    CHECK(rsx_ww_begin(w, a, 1, &sa));
    CHECK(rsx_ww_begin(w, b, 1, &sb));
    CHECK(rsx_ww_same(w, a, 1, &sa));
    vm_base[0x1001] ^= 1;
    CHECK(!rsx_ww_same(w, b, 1, &sb)); /* B harvests/resets A's page */
    CHECK(!rsx_ww_same(w, a, 1, &sa)); /* A must still see that write */
    CHECK(rsx_ww_begin(w, a, 1, &sa));
    CHECK(rsx_ww_same(w, a, 1, &sa));
    vm_base[0x1002] ^= 1; /* write between begin and the data read */
    volatile u8 read_after_begin = vm_base[0x1002]; (void)read_after_begin;
    CHECK(!rsx_ww_same(w, a, 1, &sa));

    RsxWwRange cross[] = {{0x1FFF, 2}, {0x5001, 80}};
    CHECK(rsx_ww_begin(w, cross, 2, &sa));
    vm_base[0x2000] ^= 1;
    CHECK(!rsx_ww_same(w, cross, 2, &sa));
    CHECK(rsx_ww_begin(w, cross, 2, &sa));
    vm_base[0x5004] ^= 1;
    CHECK(!rsx_ww_same(w, cross, 2, &sa));
    CHECK(rsx_ww_begin(w, a, 1, &sa));
    RsxWwRange remap[] = {{0x3000, 64}};
    CHECK(!rsx_ww_same(w, remap, 1, &sa));
    CHECK(!rsx_ww_begin(w, a, 0, &sb));
    RsxWwRange overflow[] = {{0xFFFFFFF0u, 32}};
    CHECK(!rsx_ww_begin(w, overflow, 1, &sb));
    RsxWwRange oversized[] = {{0x1000, RSX_WW_MAX_BYTES + 1}};
    CHECK(!rsx_ww_begin(w, oversized, 1, &sb));
    CHECK(VirtualAlloc(vm_base + 0xFFFFF000ull, 4096, MEM_COMMIT, PAGE_READWRITE));
    RsxWwRange last[] = {{0xFFFFFFF0u, 16}};
    CHECK(rsx_ww_begin(w, last, 1, &sb));
    vm_base[0xFFFFFFFFull] = 1;
    CHECK(!rsx_ww_same(w, last, 1, &sb));
    CHECK(rsx_ww_init(w, vm_base, 0x100000000ull));
    CHECK(!rsx_ww_same(w, a, 1, &sa)); /* lifetime/cookie changed */
    rsx_ww_close(w);

    u8* plain = VirtualAlloc(NULL, 65536, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    CHECK(plain && rsx_ww_init(w, plain, 65536));
    CHECK(!rsx_ww_begin(w, a, 1, &sa)); /* untracked allocation: fail closed */
    CHECK(w->failed && w->failures == 1);
    CHECK(!rsx_ww_same(w, a, 1, &sa));
    rsx_ww_close(w); VirtualFree(plain, 0, MEM_RELEASE); free(w);
    puts("PASS tracker: shared pages, writes during reads, disjoint/unaligned spans, remaps, 4GB bounds, lifetime, API failure");
}

static void cache_tests(int mode)
{
    s_vc = calloc(VC_N, sizeof(*s_vc));
    s_vper_mirror = malloc(VPER_BYTES);
    s_vraw_mapped = malloc(3 * VRAW_BYTES);
    CHECK(s_vc && s_vper_mirror && s_vraw_mapped);
    GfStream stream = {16, 0, 0x8000, 0x8010};
    GfPlace pl;
    memset(vm_base + 0x8000, 0x23, 4096);
    CHECK(!vc_place(&stream, 0, 127, &pl));
    ++s_vc_frame;
    CHECK(vc_place(&stream, 0, 127, &pl));
    CHECK(!memcmp(s_vper_mirror + pl.dst - 2 * VRAW_BYTES, vm_base + 0x8000, 2048));
    CHECK(vc_place(&stream, 0, 127, &pl));
    if (mode) CHECK(s_vwatch_hits > 0);
    /* Reach the legacy eight-clean-frame threshold, then mutate mid-frame. */
    for (int i = 0; i < 12; ++i) { ++s_vc_frame; CHECK(vc_place(&stream, 0, 127, &pl)); }
    vm_base[0x8010] = 0xA9;
    CHECK(vc_place(&stream, 0, 127, &pl));
    if (mode) CHECK(s_vper_mirror[pl.dst - 2 * VRAW_BYTES + 16] == 0xA9);
    /* Stream B resets a page shared with A. The real cache must invalidate A. */
    GfStream other = {16, 0, 0x8800, 0x8810};
    CHECK(!vc_place(&other, 0, 7, &pl)); ++s_vc_frame;
    CHECK(vc_place(&stream, 0, 127, &pl));
    vm_base[0x8030] = 0xB7;
    CHECK(vc_place(&other, 0, 7, &pl));
    CHECK(vc_place(&stream, 0, 127, &pl));
    if (mode) CHECK(s_vper_mirror[pl.dst - 2 * VRAW_BYTES + 48] == 0xB7);

    /* Non-contiguous IO pages and a clean remap: save/compare exact ranges. */
    RsxWwRange ranges[RSX_WW_RANGES];
    mappings[1] = 0x300000;
    CHECK(vraw_watch_ranges(1, 0xFFFF0, 64, ranges) == 2);
    CHECK(ranges[0].ea == 0xFFFF0 && ranges[1].ea == 0x300000);
    mappings[1] = 0x100000;
    CHECK(vraw_watch_ranges(1, 0xFFFF0, 64, ranges) == 1);
    CHECK(!vraw_watch_ranges(1, 0xFFFFFFF0u, 64, ranges));
    if (mode) {
        /* Start fresh rather than inherit the deliberate dirty-stream strikes. */
        GfStream mapped = {16, 1, 0x10000, 0x10010};
        CHECK(!vc_place(&mapped, 0, 7, &pl)); ++s_vc_frame;
        memset(vm_base + 0x10000, 0x31, 128);
        memset(vm_base + 0x210000, 0x62, 128);
        CHECK(vc_place(&mapped, 0, 7, &pl));
        CHECK(vc_place(&mapped, 0, 7, &pl));
        mappings[0] = 0x200000; /* no writes after this remap */
        CHECK(vc_place(&mapped, 0, 7, &pl));
        CHECK(s_vper_mirror[pl.dst - 2 * VRAW_BYTES] == 0x62);
        mappings[0] = 0;
        /* API failure must use byte comparisons even for a formerly stable entry. */
        rsx_ww_fail(&s_vwatch);
        vm_base[0x210000] = 0x73;
        CHECK(vc_place(&mapped, 0, 7, &pl));
        CHECK(s_vper_mirror[pl.dst - 2 * VRAW_BYTES] == 0x31);
        CHECK(!s_vwatch_bad);
    }
    vc_watch_stats();
    printf("PASS actual vc_place: mode=%d hits=%llu compared=%llu mismatches=%llu\n", mode, s_vwatch_hits, s_vs_vchitb, s_vwatch_bad);
    printf("cache counters: hits=%llu free=%llu misses=%llu flushes=%llu copies=%llu bytes=%llu\n",
           s_vs_vchit, s_vs_vcfree, s_vs_vcmiss, s_vs_vcflush, s_vs_vccopy, s_vs_vccopyb);
    rsx_ww_close(&s_vwatch);
    free(s_vc); free(s_vper_mirror); free(s_vraw_mapped);
}

/* Verification must catch deliberately stale data, disable skipping and let
 * the real cache refresh it. This simulates a broken/missing dirty report. */
static void verification_test(int mode)
{
    if (mode != 2 && !getenv("RSX_VTXCACHE_VERIFY")) return;
    CHECK(rsx_ww_init(&s_vwatch, vm_base, 0x100000000ull));
    s_vper_mirror = malloc(256); CHECK(s_vper_mirror);
    VcEnt entry = {0}; entry.src_lo = 0x5000; entry.len = 128;
    vraw_watch_begin(0, entry.src_lo, entry.len, &entry.watch);
    memcpy(s_vper_mirror, vm_base + entry.src_lo, entry.len);
    s_vper_mirror[10] ^= 1; /* cache stale, source pages still clean */
    CHECK(!vc_watch_reuse(&entry, 0, getenv("RSX_VTXCACHE_VERIFY") != NULL));
    CHECK(s_vwatch_bad == 1 && s_vwatch.failed && !entry.watch.stamp);
    rsx_ww_close(&s_vwatch); free(s_vper_mirror);
    puts("PASS verification: deliberately stale cache detected and skipping disabled");
}

int main(int argc, char** argv)
{
    const int mode = argc > 1 ? atoi(argv[1]) : 1;
    if (argc > 2) { reservation_test(mode); return 0; }
    vm_base = VirtualAlloc(NULL, (SIZE_T)0x100000000ull, MEM_RESERVE | MEM_WRITE_WATCH, PAGE_NOACCESS);
    CHECK(vm_base && VirtualAlloc(vm_base, 4u << 20, MEM_COMMIT, PAGE_READWRITE));
    for (u32 i = 0; i < 16; ++i) mappings[i] = i << 20;
    tracker_tests(); cache_tests(mode); verification_test(mode);
    VirtualFree(vm_base, 0, MEM_RELEASE);
    vm_base = NULL; reservation_test(mode);
    return 0;
}
